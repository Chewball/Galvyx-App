enum class HotelAuditStatus(val label: String) {
    PENDING("Pending"),
    COMPLETE("Complete"),
    INACCESSIBLE("Inaccessible"),
    DEFERRED("Deferred");

    companion object {
        fun fromRaw(raw: String?): HotelAuditStatus = values().firstOrNull {
            it.name.equals(raw, ignoreCase = true) || it.label.equals(raw, ignoreCase = true)
        } ?: PENDING
    }
}

